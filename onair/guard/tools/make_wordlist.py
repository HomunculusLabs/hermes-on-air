"""Developer tool: regenerate onair/guard/wordlist_en.py from a SCOWL / ESDB word list.

Not imported by the plugin and never run at runtime. It reads a local file and does no network I/O.

Get the source list once from the SCOWL web app (size 50, US spelling, diacritics stripped):

    http://app.aspell.net/create?max_size=50&spelling=US&max_variant=0&diacritic=strip&special=hacker&download=wordlist&encoding=utf-8&format=inline

then run it as a module from the repository root (write to a temporary file first: the tool imports the
word filter's lists from this package):

    python3 -m onair.guard.tools.make_wordlist en50.txt > /tmp/wordlist_en.py
    mv /tmp/wordlist_en.py onair/guard/wordlist_en.py

Kept: lower-case forms made only of the letters a-z (possessives and entries with other characters dropped),
deduplicated and sorted. The license header of the source list is copied verbatim into the module docstring
and into WORDLIST-LICENSE.txt, as its license requires.

Dictionary words that are also forms the word filter lists (onair/wordfilter) are not written in plain text.
They go into CONCEALED_ROT13, ROT13-encoded like the filter's own lists, and onair/guard/lexicon.py adds them
back when it builds the dictionary, so the set of known words is unchanged. The few benign forms the filter
deliberately leaves alone stay in the plain list.
"""
from __future__ import annotations

import codecs
import re
import sys


def listed_forms() -> set[str]:
    """Every form the word filter matches, decoded from its ROT13 lists (benign exclusions left out)."""
    from ...wordfilter import _EXCLUDED_FORMS, _WORDS, _forms

    return set().union(*(_forms(root) for _, root in _WORDS)) - set(_EXCLUDED_FORMS)


def _write_pieces(out, words: list[str]) -> None:
    # wrap the space-joined body in ~100-character string pieces so the module stays readable by tools
    piece = []
    size = 0
    for w in words:
        piece.append(w)
        size += len(w) + 1
        if size >= 100:
            out.write(f'    "{" ".join(piece)} "\n')
            piece, size = [], 0
    if piece:
        out.write(f'    "{" ".join(piece)}"\n')


def main(path: str) -> None:
    lines = open(path, encoding="utf-8").read().split("\n")
    cut = lines.index("---")
    header = "\n".join(lines[:cut]).rstrip()
    words = set()
    for raw in lines[cut + 1:]:
        w = raw.strip()
        if not w or "'" in w:
            continue
        low = w.lower()
        if re.fullmatch(r"[a-z]+", low):
            words.add(low)
    concealed = words & listed_forms()
    plain = sorted(words - concealed)
    out = sys.stdout
    out.write('"""English word list for the On Air output guard ("is this a real word" checks).\n\n')
    out.write("GENERATED by onair/guard/tools/make_wordlist.py. Do not edit by hand.\n\n")
    out.write(f"{len(words)} lower-case a-z words from the source list below (SCOWL / ESDB, size 50, en_US):\n")
    out.write(f"{len(plain)} in WORDS and {len(concealed)} in CONCEALED_ROT13. The concealed ones are the dictionary\n")
    out.write("words that the word filter also lists; they are ROT13-encoded like the filter's own lists and\n")
    out.write("onair/guard/lexicon.py adds them back when it builds the dictionary.\n")
    out.write("The source's license notice follows verbatim (also in WORDLIST-LICENSE.txt):\n\n")
    out.write(header.replace("\\", "\\\\").replace('"""', "'''"))
    out.write('\n"""\n\n')
    out.write(f"WORD_COUNT = {len(words)}\n")
    out.write("WORDS = (\n")
    _write_pieces(out, plain)
    out.write(")\n")
    out.write("CONCEALED_ROT13 = (\n")
    _write_pieces(out, sorted(codecs.encode(w, "rot_13") for w in concealed))
    out.write(")\n")


if __name__ == "__main__":
    main(sys.argv[1])
