const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const { JSDOM } = require('jsdom');
const dom = new JSDOM('<!doctype html><div id="root"></div>', {url:'http://localhost/'});
global.window=dom.window; global.document=dom.window.document;
global.IS_REACT_ACT_ENVIRONMENT=true;
const React=require('react'); const {createRoot}=require('react-dom/client'); const {act}=React;
let Page; const calls=[];
let stage=false, refusal=false, unblock=null;
let waitAction=false;
const boxes={scene:'On Air: Boxes', slots:{main:'slides',sub1:'scene',sub2:'empty'}, arrangement:'side', available:{slides:{available:true},scene:{available:true},window:{available:false,reason:'Choose and confirm a window.'},empty:{available:true}}};
window.__HERMES_PLUGIN_SDK__={React,fetchJSON:async (url,opts)=>{
  const path=url.replace('/api/plugins/on-air/','');
  if(opts){
    calls.push([path,JSON.parse(opts.body)]);
    if(path==='host/turn') return {ok:false,message:'The show changed.'};
    if(waitAction) await new Promise(resolve=>{unblock=resolve});
    if(refusal) return {ok:false,error:'Server refused this change.',next_human_action:'Try another source.'};
    return {ok:true};
  }
  if(path==='views/state') return {ok:true,connected:true,program_scene:'On Air: Boxes',approved_scenes:['On Air: Boxes'],scenes_present:{'On Air: Boxes':true},stream:{active:false},boxes,window:{exists:false,ready:false,prerequisites:['Prepare the window.']},layout:{current:{}},stage_profile:stage};
  if(path==='state') return {mode:'approval',live:true,privacy:false,epoch:7,voice_boot:'a'.repeat(32),seq:1,host_turns:{enabled:true}};
  if(path==='pending') return {epoch:7,pending:[]};
  if(path.startsWith('receipts')) return {receipts:[]};
  if(path==='alerts') return {alerts:{}};
  if(path==='alerts/recent') return {alerts:[]};
  return {};
}};
window.__HERMES_PLUGINS__={register:(_,p)=>Page=p};
vm.runInThisContext(fs.readFileSync('dashboard/dist/index.js','utf8'));
const root=createRoot(document.getElementById('root'));
const settle=()=>new Promise(r=>setTimeout(r,40));
(async()=>{
  await act(async()=>{root.render(React.createElement(Page));await settle()});
  await act(async()=>{document.querySelector('.onair-secondary summary').click(); [...document.querySelectorAll('.onair-secondary button')].find(b=>b.textContent==='Full desk (advanced)').click();await settle()});
  const panel=document.querySelector('[aria-labelledby="onair-views"]');
  assert(panel && panel.textContent.includes('Main') && panel.textContent.includes('Sub 2'));
  assert(panel.textContent.includes('Choose and confirm a window.'));
  const select=panel.querySelector('select[aria-label="Sub 2 source"]');
  assert(select && [...select.options].find(o=>o.value==='window').disabled);
  await act(async()=>{select.value='scene';select.dispatchEvent(new window.Event('change',{bubbles:true}));await settle()});
  assert.deepEqual(calls.find(x=>x[0]==='views/boxes'),['views/boxes',{op:'put',slot:'sub2',source:'scene'}]);
  assert.equal(select.value, 'empty', 'a successful request does not replace the OBS readback');
  waitAction=true; refusal=true;
  await act(async()=>{select.value='scene';select.dispatchEvent(new window.Event('change',{bubbles:true}));await settle()});
  assert.equal(panel.getAttribute('aria-busy'), 'true');
  assert(panel.textContent.includes('Checking OBS'));
  assert([...panel.querySelectorAll('button,select')].every(el=>el.disabled), 'all view controls lock while awaiting readback');
  await act(async()=>{unblock(); await settle()});
  assert.equal(select.value, 'empty');
  assert(panel.textContent.includes('Server refused this change.'));
  assert(panel.textContent.includes('Try another source.'));
  waitAction=false; refusal=false;
  waitAction=true;
  await act(async()=>{[...panel.querySelectorAll('button')].find(b=>b.textContent==='Swap Main and Sub 1').click();await settle()});
  boxes.slots.main='scene'; boxes.slots.sub1='slides';
  await act(async()=>{unblock();await settle()});
  assert.equal(panel.querySelector('[aria-label="Main source"]').value,'scene', 'the server readback wins');
  assert.equal(panel.querySelector('[aria-label="Sub 1 source"]').value,'slides');
  waitAction=false;
  const host=document.querySelector('[aria-label="Host line"]');
  assert(host);
  const input=host.querySelector('input');
  const setter=Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype,'value').set;
  await act(async()=>{setter.call(input,'Hello co-host');input.dispatchEvent(new window.Event('input',{bubbles:true}));await settle()});
  await act(async()=>{host.querySelector('button').click();await settle()});
  const post = calls.find(x=>x[0]==='host/turn');
  assert.match(post[1].id,/^[0-9a-f]{32}$/);
  assert.deepEqual(post,['host/turn',{text:'Hello co-host',epoch:7,boot:'a'.repeat(32),id:post[1].id}]);
  assert(host.textContent.includes('The show changed.'));
  stage=true;
  await act(async()=>{root.render(React.createElement(Page,{key:'stage'}));await settle()});
  const stagePanel=document.querySelector('[aria-labelledby="onair-views"]');
  assert(stagePanel.textContent.includes('This stage profile cannot change views from the desk.'));
  assert(stagePanel.textContent.includes('“Please change the view.”'));
  assert([...stagePanel.querySelectorAll('button,select')].every(el=>el.disabled));
  assert(stagePanel.textContent.includes('Main: Scene; Sub 1: Slides; Sub 2: Empty.'));
  await act(async()=>root.unmount());
  console.log('views behavior passed');
})().catch(e=>{console.error(e);process.exitCode=1;root.unmount()});
